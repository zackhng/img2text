"""Inspect downloaded datasets and write a manifest of what each one actually contains.

For every dataset folder under data_cache/raw/, reports file counts, parquet row counts,
column names and one sample row. Writes docs/dataset_manifest.md.

Usage:
    uv run python scripts/inspect_datasets.py
"""

from __future__ import annotations

from pathlib import Path

import pyarrow.parquet as pq

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data_cache" / "raw"
OUT = ROOT / "docs" / "dataset_manifest.md"

IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp", ".bmp"}


def summarize_parquet(files: list[Path]) -> dict:
    rows = 0
    columns: list[str] = []
    for f in files:
        meta = pq.ParquetFile(f)
        rows += meta.metadata.num_rows
        if not columns:
            columns = meta.schema_arrow.names
    return {"rows": rows, "columns": columns}


def sample_row(files: list[Path], columns: list[str]) -> str:
    """Return a short printable sample of the first row, truncating long values."""
    if not files:
        return ""
    table = pq.ParquetFile(files[0]).read_row_group(0, columns=None)
    if table.num_rows == 0:
        return ""
    row = {c: table.column(c)[0].as_py() for c in table.column_names}
    out = []
    for k, v in row.items():
        if isinstance(v, dict) and "bytes" in v:
            v = f"<image {len(v['bytes'] or b'')} bytes>"
        elif isinstance(v, bytes):
            v = f"<{len(v)} bytes>"
        text = str(v).replace("\n", "\\n")
        out.append(f"- `{k}`: {text[:140]}")
    return "\n".join(out)


def inspect_dataset(folder: Path) -> str:
    all_files = [p for p in folder.rglob("*") if p.is_file() and ".cache" not in p.parts]
    parquet = sorted(p for p in all_files if p.suffix == ".parquet")
    images = [p for p in all_files if p.suffix.lower() in IMAGE_EXTS]
    size_gb = sum(p.stat().st_size for p in all_files) / 1e9

    lines = [f"## {folder.name}", "", f"- files: {len(all_files)} ({size_gb:.2f} GB)"]
    lines.append(f"- loose image files: {len(images)}")
    if parquet:
        info = summarize_parquet(parquet)
        splits = sorted({p.name.split("-")[0] for p in parquet})
        lines.append(f"- parquet shards: {len(parquet)} (splits: {', '.join(splits)})")
        lines.append(f"- rows: {info['rows']:,}")
        lines.append(f"- columns: {', '.join(f'`{c}`' for c in info['columns'])}")
        sample = sample_row(parquet, info["columns"])
        if sample:
            lines += ["", "Sample row:", sample]
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    if not RAW.exists():
        raise SystemExit(f"no downloads yet: {RAW} does not exist")

    sections = [
        "# Downloaded dataset manifest",
        "",
        "Generated by `scripts/inspect_datasets.py` from `data_cache/raw/`. Re-run after downloads.",
        "",
    ]
    for folder in sorted(p for p in RAW.iterdir() if p.is_dir()):
        print(f"inspecting {folder.name} ...", flush=True)
        sections.append(inspect_dataset(folder))

    OUT.write_text("\n".join(sections), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
